export const DICTS: Record<Lang, Dict> = { en, fr };

export function detectLang(): Lang {
  try {
    const saved = window.localStorage.getItem("confam.lang");
    if (saved === "en" || saved === "fr") return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function saveLang(lang: Lang): void {
  try {
    window.localStorage.setItem("confam.lang", lang);
  } catch {
    /* storage unavailable */
  }
}

export const LangContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: "en",
  t: en,
  setLang: () => {},
});

export const useT = (): { lang: Lang; t: Dict; setLang: (l: Lang) => void } => useContext(LangContext);
